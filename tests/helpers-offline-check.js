// Real worker and actual registered helpers; fresh context, no network after activation.
async (page) => {
  const context = await page.context().browser().newContext({ viewport: { width: 320, height: 700 } });
  const app = await context.newPage();
  const results = [];
  const errors = [];
  const requests = [];
  app.on('pageerror', error => errors.push(error.message));
  app.on('request', request => requests.push(request.url()));
  function check(condition, label) { if (!condition) throw new Error(label); results.push(label); }
  async function open(id, selector) {
    await app.locator('.home-accordion').last().evaluate(element => { element.open = true; });
    await app.locator(`#allHelperList [data-helper="${id}"]`).click();
    await app.waitForSelector(selector);
  }
  try {
    await app.goto('http://127.0.0.1:8080/manifest.webmanifest');
    await app.evaluate(async () => { await caches.open('foreign-cache'); await caches.open('0815-v0.4.1'); });
    await app.goto('http://127.0.0.1:8080/');
    await app.evaluate(() => navigator.serviceWorker.ready);
    await app.waitForFunction(() => !!navigator.serviceWorker.controller);
    const state = await app.evaluate(async () => {
      const { version } = await (await fetch('/package.json')).json();
      const { HELPERS } = await import('/src/helpers/registry.js');
      const paths = (await (await caches.open(`0815-v${version}`)).keys()).map(request => new URL(request.url).pathname);
      const expected = HELPERS.flatMap(helper => [`/src/helpers/${helper.id}/index.js`, ...(helper.offlineAssets || []).map(path => new URL(path, location.href).pathname)]);
      return { version, paths, expected, caches: await caches.keys() };
    });
    check(state.caches.includes(`0815-v${state.version}`) && !state.caches.includes('0815-v0.4.1') && state.caches.includes('foreign-cache'), 'Worker activates the current release and preserves foreign caches');
    check(state.expected.every(path => state.paths.includes(path)), 'Worker precaches every registered helper module and declared asset');
    check(['/src/notes.js', '/src/note-views.js', '/src/note-presentation.js', '/assets/notes.css'].every(path => state.paths.includes(path)), 'Worker precaches the note views and their separate presentation assets');
    await context.setOffline(true);
    await app.reload();
    await open('discount', '#discountForm');
    await app.locator('input[name="price"]').fill('75,00');
    await app.locator('input[name="discount"]').fill('30');
    await app.locator('#discountForm button').click();
    await app.waitForFunction(() => document.querySelector('#discountResult').textContent.replace(/\s/g, '') === '52,50€');
    check(await app.evaluate(async () => (await (await import('/src/db.js')).list('entries')).some(entry => entry.helperId === 'discount' && entry.calculations[0].priceCents === 7500)), 'Offline discount calculation commits to IndexedDB');
    await app.locator('#backButton').click();
    await app.reload();
    await open('discount', '#discountForm');
    check((await app.locator('.discount-history li').textContent()).replace(/\s/g, '').includes('75,00€·30%→52,50€'), 'Offline reload restores the discount history');
    await app.locator('#backButton').click();
    await open('drink', '#drinkRecord');
    await app.locator('#drinkRecord').click();
    await app.waitForFunction(() => !document.querySelector('.drink-last').hidden && !document.querySelector('#drinkRecord').disabled);
    check(await app.evaluate(async () => (await (await import('/src/db.js')).list('entries')).some(entry => entry.helperId === 'drink' && entry.recordedAt === entry.createdAt)), 'Offline drink action commits its minimal event');
    await app.locator('#backButton').click();
    await app.reload();
    await open('drink', '#drinkRecord');
    check(await app.locator('.drink-history li').count() === 1 && await app.locator('#drinkRecord').textContent() === 'Ja, gerade', 'Offline reload restores the documented drink');
    await app.locator('#backButton').click();
    await open('pain', '#painAreaForm');
    await app.locator('input[name="bodyArea"][value="Bauch"]').check();
    await app.locator('#painAreaForm button').click();
    await app.waitForSelector('#painEntryForm');
    await app.locator('input[name="intensity"][value="4"]').check();
    await app.locator('#painEntryForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('.pain h2')?.textContent === 'Bauch · 4 gespeichert');
    await app.locator('[data-pain="done"]').click();
    await app.reload();
    await open('pain', '.pain-last-value');
    check((await app.locator('.pain-last-value').textContent()).includes('Bauch · 4'), 'Pain still saves and restores offline alongside the new helper');
    await app.locator('#backButton').click();
    await app.locator('[data-composer="note"]').click();
    await app.locator('#noteText').fill('Offline-Notiz');
    await app.locator('#noteForm button').click();
    await app.locator('#quickNoteContextDone').click();
    await app.waitForSelector('#quickComposer', { state: 'hidden' });
    await app.locator('#menuButton').click();
    await app.locator('[data-view="notes"]').click();
    await app.waitForSelector('.read-text');
    check(await app.locator('.read-text').textContent() === 'Offline-Notiz', 'Notes capture and read work with the real worker offline');
    await app.locator('#backButton').click();
    await app.reload();
    await app.locator('#menuButton').click();
    await app.locator('[data-view="notes"]').click();
    await app.waitForSelector('.read-text');
    check(await app.locator('.read-text').textContent() === 'Offline-Notiz', 'Offline reload restores the notes view data');
    await app.locator('#readHost [data-note]').click();
    await app.locator('#noteEdit').click();
    await app.locator('#noteEditText').fill('Offline bearbeitet');
    await app.locator('#noteEditForm button[type="submit"]').click();
    await app.waitForSelector('#noteEdit');
    await app.locator('#noteContext').click();
    await app.locator('#noteChooseTime').click();
    const bucket = await app.evaluate(async () => (await import('/src/context.js')).timeBucket());
    await app.locator(`#noteContextForm input[value="${bucket}"]`).check();
    await app.locator('#noteContextForm button[type="submit"]').click();
    await app.waitForSelector('#noteContextDone');
    await app.locator('#noteContextDone').click();
    await app.locator('#backButton').click();
    await app.locator('#backButton').click();
    await app.reload();
    await app.locator('#nowRows [data-note]').click();
    await app.waitForSelector('#noteEdit');
    check(await app.locator('.note-text').textContent() === 'Offline bearbeitet' && (await app.locator('.note-dates').textContent()).includes('Bearbeitet') && await app.locator('.note-links li').count() === 1, 'Offline edit, context and Now survive reload with the real worker');
    await app.locator('#noteDelete').click();
    await app.locator('#noteDeleteConfirm').click();
    await app.waitForSelector('#view-dashboard');
    await app.waitForFunction(() => !document.querySelector('#nowRows [data-note]'));
    check(await app.evaluate(async () => !(await (await import('/src/db.js')).list('entries', { prune: false })).some(entry => entry.type === 'note')), 'Offline delete removes the contextual note and returns to its dashboard parent');
    await app.locator('#menuButton').click();
    await app.locator('[data-view="notes"]').click();
    await app.waitForFunction(() => document.querySelector('#readHost').textContent === 'Noch keine Notizen.');
    check(await app.locator('#readHost').textContent() === 'Noch keine Notizen.', 'Offline delete also leaves the notes overview empty');
    await app.locator('#backButton').click();
    await app.locator('[data-composer="person"]').click();
    await app.waitForSelector('#personForm');
    await app.locator('input[name="newName"]').fill('Offline-Person');
    await app.locator('#personForm textarea').fill('Schuhgröße 40');
    await app.locator('#personForm button').click();
    await app.locator('#quickNoteContextDone').click();
    await app.waitForSelector('#quickComposer', { state: 'hidden' });
    await app.locator('#menuButton').click();
    await app.locator('[data-view="people"]').click();
    await app.locator('[data-person]').click();
    await app.waitForSelector('#read-references');
    check(await app.locator('#focusTitle').textContent() === 'Offline-Person' && await app.locator('.read-text').textContent() === 'Schuhgröße 40', 'People and references read offline without extra assets or requests');
    await app.locator('#backButton').click();
    await app.waitForSelector('[data-person]');
    check(await app.locator('#focusTitle').textContent() === 'Personen', 'Person Back restores its list offline');
    // Controlled existing geolocation mechanism, with local data and the real worker.
    const locationStub = () => Object.defineProperty(navigator, 'geolocation', { configurable: true, value: {
      getCurrentPosition(success) { success({ coords: { latitude: 50, longitude: 8, accuracy: 10 } }); }
    } });
    await app.addInitScript(locationStub);
    await app.evaluate(locationStub);
    await app.evaluate(async () => {
      await (await import('/src/db.js')).put('places', { id: 'offline-home', name: 'Bei Offline-Person', lat: 50, lon: 8, radius: 250, createdAt: 1 });
    });
    await app.locator('[data-person]').click();
    await app.locator('#readHost [data-note]').click();
    await app.locator('#noteEdit').click();
    await app.locator('#noteEditText').fill('Welche Schuhgröße brauchst du?');
    await app.locator('#noteEditForm button[type="submit"]').click();
    await app.waitForSelector('#noteEdit');
    await app.locator('#noteContext').click();
    await app.locator('#noteChoosePlace').click();
    await app.locator('#noteContextForm input[value="offline-home"]').check();
    await app.locator('#noteContextForm button[type="submit"]').click();
    await app.waitForSelector('#noteContextDone');
    await app.locator('#noteChooseTime').click();
    await app.locator(`#noteContextForm input[value="${bucket}"]`).check();
    await app.locator('#noteContextForm button[type="submit"]').click();
    await app.waitForSelector('#noteContextDone');
    await app.locator('#noteContextDone').click();
    await app.locator('#backButton').click();
    await app.waitForSelector('#readHost [data-note]');
    await app.locator('#backButton').click();
    await app.waitForSelector('[data-person]');
    await app.locator('#backButton').click();
    await app.reload();
    await app.locator('#nowRows [data-note]').click();
    await app.waitForSelector('#noteEdit');
    check(await app.locator('.note-text').textContent() === 'Welche Schuhgröße brauchst du?' && await app.locator('.note-detail .note-person-name').textContent() === 'Offline-Person' && await app.locator('.note-links li').count() === 2, 'Person-note editing, both contexts and Now survive a real offline reload');
    await app.locator('#noteDelete').click();
    await app.locator('#noteDeleteConfirm').click();
    await app.waitForSelector('#view-dashboard');
    await app.waitForFunction(() => !document.querySelector('#nowRows [data-note]'));
    check(await app.evaluate(async () => !(await (await import('/src/db.js')).list('entries', { prune: false })).some(entry => entry.type === 'person-note') && (await (await import('/src/db.js')).list('people')).length === 1), 'Person-note deletion works offline and keeps the person');
    check(requests.every(url => url.startsWith('http://127.0.0.1:8080/')), 'Offline helper flows request no external resources');
    check(errors.length === 0, `No offline browser errors: ${errors.join(', ')}`);
    return results;
  } finally { await context.close(); }
}
