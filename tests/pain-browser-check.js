// Actual registered helper, real IndexedDB, isolated browser context. No test library added.
async (page) => {
  const context = await page.context().browser().newContext({ serviceWorkers: 'block', viewport: { width: 320, height: 740 } });
  const app = await context.newPage();
  const requests = [];
  const errors = [];
  app.on('request', request => requests.push(request.url()));
  app.on('pageerror', error => errors.push(error.message));
  const results = [];
  function check(condition, message) {
    if (!condition) throw new Error(message);
    results.push(message);
  }
  async function stored() { return app.evaluate(async () => (await (await import('/src/db.js')).list('entries')).filter(entry => entry.helperId === 'pain')); }
  async function open() {
    await app.locator('.home-accordion').last().evaluate(element => { element.open = true; });
    await app.locator('#allHelperList [data-helper="pain"]').click();
    await app.waitForSelector('.pain-content form, .pain-content h2');
  }
  async function next() { await app.locator('#painAreaForm button[type="submit"]').click(); await app.waitForSelector('#painEntryForm'); }
  async function another() { await app.locator('[data-pain="another"]').click(); await app.waitForSelector('#painAreaForm'); }
  async function settings() { await app.locator('#helperSettingsButton').click(); await app.waitForSelector('#helperSettingsForm'); }
  async function savedRule() { return app.evaluate(async () => (await (await import('/src/db.js')).get('helperRules', 'pain'))); }
  async function saveRule() { await app.locator('#helperSettingsForm button[type="submit"]').click(); await app.waitForFunction(() => !document.querySelector('#helperSettingsForm').dataset.saving); }
  async function reflow(message) { check(await app.evaluate(() => document.documentElement.scrollWidth <= innerWidth), message); }
  try {
    await app.goto('http://127.0.0.1:8080/');
    await app.waitForSelector('#allHelperList [data-helper="pain"]', { state: 'attached' });
    await open();
    check(await app.locator('#view-dashboard').isVisible() === false, 'Pain is in the shell focus view');
    check(await app.evaluate(async () => !(await (await import('/src/db.js')).get('settings', 'usage:pain'))), 'Viewing pain does not record use');
    check(await app.locator('.pain-guidance').isVisible(), 'Guidance is enabled on first use');
    check(await app.getByRole('button', { name: 'Hinweise ausblenden', exact: true }).isVisible(), 'Guidance control has an accessible action name');
    check(await app.locator('input[name="intensity"]').count() === 0, 'First step asks only for the body area');
    check(await app.locator('.pain fieldset').getAttribute('aria-describedby') === 'pain-area-hint', 'Area instructions are connected to their group');
    check(!await app.locator('#painAreaForm').evaluate(form => form.checkValidity()), 'Area step requires a selection');
    const areaTree = await app.locator('.pain-content').ariaSnapshot();
    check(areaTree.includes('group "Wo tut es gerade weh?"') && areaTree.includes('radio "Kopf"'), 'Accessibility tree exposes the area question and named native radios');
    await reflow('Area step fits 320 CSS px');
    await app.keyboard.press('Tab');
    check(await app.locator('input[name="bodyArea"][value="Kopf"]').evaluate(element => element === document.activeElement), 'Tab from the area question reaches its first radio');
    await app.locator('input[name="bodyArea"][value="Bauch"]').check();
    check(await app.locator('#painAreaForm').isVisible(), 'Selecting an area does not automatically advance');
    await app.locator('#painAreaForm button[type="submit"]').focus();
    await app.keyboard.press('Enter');
    await app.waitForSelector('#painEntryForm');
    check(await app.locator('input[name="bodyArea"]').count() === 0, 'Second step asks only for intensity');
    check(await app.evaluate(() => document.activeElement === document.querySelector('.pain legend')), 'Focus follows Weiter to the intensity question');
    check(await app.locator('.pain fieldset').getAttribute('aria-describedby') === 'pain-scale pain-intensity-hint', 'Intensity instructions and anchors are connected to their group');
    const intensityTree = await app.locator('.pain-content').ariaSnapshot();
    check(intensityTree.includes('group "Wie stark ist der Schmerz gerade?"') && intensityTree.includes('radio "10"'), 'Accessibility tree exposes the intensity question and all scale choices');
    check(!await app.locator('#painEntryForm').evaluate(form => form.checkValidity()), 'Area alone cannot save');
    check((await stored()).length === 0, 'No event before complete minimum input');
    await app.locator('input[name="intensity"][value="1"]').focus();
    await app.keyboard.press('Space');
    for (let i = 0; i < 3; i++) await app.keyboard.press('ArrowRight');
    check(await app.locator('input[name="intensity"][value="4"]').isChecked(), 'Intensity radios work with keyboard arrows');
    check(await app.locator('input[name="intensity"][value="4"]').evaluate(element => getComputedStyle(element.closest('label')).outlineStyle === 'solid'), 'Intensity choice has visible keyboard focus');
    await reflow('Minimum input fits 320 CSS px');
    await app.locator('[data-pain="change-area"]').click();
    check(await app.locator('input[name="bodyArea"][value="Bauch"]').isChecked(), 'Ort ändern preserves the selected area');
    check(await app.evaluate(() => document.activeElement === document.querySelector('.pain legend')), 'Ort ändern focuses the area question');
    await next();
    check(await app.locator('input[name="intensity"][value="4"]').isChecked(), 'Ort ändern preserves the unsaved intensity');
    await app.locator('[data-pain="back"]').click();
    check(await app.locator('#painAreaForm').isVisible(), 'Zurück returns to the area step');
    await next();
    const before = Date.now();
    await app.locator('#painEntryForm button[type="submit"]').focus();
    await app.keyboard.press('Enter');
    await app.waitForFunction(() => document.querySelector('.pain-status')?.textContent === 'Eintrag gespeichert.');
    const first = (await stored())[0];
    check(first.bodyArea === 'Bauch' && first.intensity === 4 && first.recordedAt >= before && first.createdAt === first.recordedAt && first.startedAt === undefined, 'Minimum event stores automatic timestamp and no inferred onset');
    check(await app.evaluate(() => document.activeElement === document.querySelector('.pain h2')), 'Focus follows save into its confirmation');
    check(await app.locator('.pain-content').textContent().then(text => text.includes('Erster dokumentierter Wert für Bauch.')), 'First value has no invented previous zero');
    check(!(await app.locator('.pain-content').textContent()).includes('Du bist fertig.') && await app.locator('[data-pain="done"]').isVisible() && await app.locator('[data-pain="details"]').isVisible(), 'Save confirmation presents its actions without moderator copy');
    check(await app.evaluate(async before => (await (await import('/src/db.js')).get('settings', 'usage:pain')).lastUsedAt >= before, before), 'Successful save records actual use');
    check(await app.getByRole('heading', { name: 'Ist der Schmerz inzwischen vorbei?' }).isVisible(), 'Schmerz weg has an explicit question and body-area context');
    await reflow('Save confirmation fits 320 CSS px');
    await app.locator('[data-pain="resolved"]').click();
    await app.waitForFunction(() => document.querySelector('.pain h2')?.textContent.includes('schmerzfrei'));
    const resolved = (await stored()).find(entry => entry.eventType === 'resolved');
    check(resolved.id !== first.id && resolved.intensity === 0 && resolved.bodyArea === first.bodyArea, 'Schmerz weg adds a separate zero event');
    check(JSON.stringify((await stored()).find(entry => entry.id === first.id)) === JSON.stringify(first), 'Schmerz weg leaves the original observation untouched');
    await app.locator('[data-pain="done"]').click();
    await open();
    check(await app.locator('.pain-last-value').textContent().then(text => text.includes('Bauch · 0 · schmerzfrei')) && await app.locator('[data-pain="resolved"]').count() === 0, 'Returning view respects the last resolved event without inferring current pain');
    await another();
    await app.locator('input[name="bodyArea"][value="Rücken"]').check();
    await next();
    await app.locator('input[name="intensity"][value="6"]').check();
    await app.locator('#painEntryForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('.pain h2')?.textContent === 'Rücken · 6 gespeichert');
    check(await app.locator('.pain-content').textContent().then(text => text.includes('Erster dokumentierter Wert für Rücken.')), 'Different body area does not compare with Bauch');
    const back = (await stored()).find(entry => entry.bodyArea === 'Rücken');
    await app.locator('[data-pain="details"]').click();
    await app.locator('input[name="quality"][value="ziehend"]').check();
    await app.locator('select[name="start"]').selectOption('yesterday');
    await app.locator('select[name="interference"]').selectOption('0');
    await app.locator('input[name="relief"][value="Medikament"]').check();
    await app.locator('textarea[name="possibleContext"]').fill('Nach dem Sitzen');
    await app.locator('textarea[name="note"]').fill('<img src="https://external.test/leak" onerror="window.xss=true">');
    await reflow('Optional details fit 320 CSS px');
    await app.locator('#painDetailsForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('.pain-status')?.textContent === 'Details gespeichert.');
    const updated = (await stored()).find(entry => entry.id === back.id);
    check(updated.recordedAt === back.recordedAt && updated.createdAt === back.createdAt && updated.intensity === 6 && updated.interference === 0 && updated.startedAt.kind === 'yesterday' && updated.relief.includes('Medikament'), 'Optional details preserve the required event and qualified onset');
    check((await stored()).length === 3, 'Details update the same event rather than duplicating it');
    await app.locator('[data-pain="details"]').click();
    check(await app.locator('select[name="start"] option[value="now"]').textContent() === 'zum Zeitpunkt der Dokumentation', 'Onset option describes the documentation time even when editing later');
    await app.locator('select[name="start"]').selectOption('now');
    await app.locator('#painDetailsForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('.pain-status')?.textContent === 'Details gespeichert.');
    check((await stored()).find(entry => entry.id === back.id).startedAt.at === back.recordedAt && (await stored()).length === 3, 'Reworded onset option retains its original timestamp and event');
    await app.locator('[data-pain="history"]').click();
    check(await app.locator('.pain-history li').count() === 1, 'History contains only the selected body area');
    check(await app.locator('.pain-history img').count() === 0 && !await app.evaluate(() => !!window.xss), 'Imported or entered HTML remains literal text in history');
    await reflow('History fits 320 CSS px');
    await app.locator('[data-pain="new"]').click();
    await app.locator('input[name="bodyArea"][value="Bauch"]').check();
    await next();
    await app.locator('input[name="intensity"][value="3"]').check();
    await app.locator('#painEntryForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('.pain h2')?.textContent === 'Bauch · 3 gespeichert');
    check(await app.locator('.pain-content').textContent().then(text => text.includes('Letzter dokumentierter Wert für Bauch: 0')), 'Previous documented value is the same-area zero event');
    await app.locator('[data-pain="history"]').click();
    check(await app.locator('.pain-history-value strong').allTextContents().then(values => JSON.stringify(values) === JSON.stringify(['3', '0 · schmerzfrei · Schmerz weg', '4'])), 'Per-area history is descending and marks conscious freedom');

    await settings();
    check(await app.locator('input[name="guidance"]').isChecked(), 'Helper settings offer enabled guidance by default');
    check(await app.locator('fieldset').filter({ has: app.getByText('Ort', { exact: true }) }).count() > 0 && await app.locator('input[name="time"]').count() === 4 && await app.locator('input[name="intervalValue"]').count() === 1, 'Pain uses the shared location, time and interval settings');
    check(await app.locator('select[name="trackingWindow"]').inputValue() === 'always', 'Unlimited retention is the explicit default');
    await app.locator('input[name="favorite"]').check();
    await app.locator('input[name="time"][value="morning"]').check();
    await app.locator('input[name="intervalValue"]').fill('1');
    await app.locator('select[name="intervalUnit"]').selectOption('hour');
    await app.locator('.interval-early-option summary').click();
    await app.locator('input[name="earlyByValue"]').fill('15');
    await app.locator('select[name="earlyByUnit"]').selectOption('minute');
    await saveRule();
    const rule = await savedRule();
    check(rule.favorite && rule.timeBuckets.includes('morning')
      && rule.interval.value === 1 && rule.interval.unit === 'hour'
      && rule.earlyBy.value === 15 && rule.earlyBy.unit === 'minute', 'Favorite and user-defined context rules persist');
    await app.locator('#backButton').click();
    await app.waitForSelector('.pain-last-value');
    await app.locator('#backButton').click();
    await app.waitForSelector('#nowRows [data-helper="pain"]');
    await app.waitForSelector('#favoriteTiles [data-helper="pain"]', { state: 'attached' });
    check(await app.locator('#favoriteTiles [data-helper="pain"]').count() === 1, 'Visible pain favorite is presented');
    await open();
    check(await app.getByRole('heading', { name: 'Zuletzt dokumentiert' }).isVisible(), 'Returning user sees the latest documented event');
    check(await app.locator('.pain-last-value').textContent().then(text => text.includes('Bauch · 3')), 'Returning view chooses only the latest body area');
    check(await app.locator('#painAreaForm').count() === 0, 'Returning user need not select the area again');
    await reflow('Returning view fits 320 CSS px');
    await app.locator('[data-pain="same-area"]').click();
    check(await app.locator('#painEntryForm').isVisible() && await app.locator('input[name="bodyArea"]').count() === 0, 'New value for the same area goes directly to intensity');
    await app.locator('[data-pain="back"]').click();
    check(await app.getByRole('heading', { name: 'Zuletzt dokumentiert' }).isVisible(), 'Zurück from quick entry restores the documented summary');
    const eventsBeforeGuidance = JSON.stringify(await stored());
    const usageBeforeGuidance = await app.evaluate(async () => (await (await import('/src/db.js')).get('settings', 'usage:pain')).lastUsedAt);
    await app.evaluate(() => { window.originalPut = IDBObjectStore.prototype.put; IDBObjectStore.prototype.put = function() { throw new DOMException('Quota', 'QuotaExceededError'); }; });
    await app.locator('[data-pain="guidance-off"]').click();
    await app.waitForFunction(() => document.querySelector('#toast').textContent.includes('Speicher voll'));
    await app.evaluate(() => { IDBObjectStore.prototype.put = window.originalPut; });
    check(await app.locator('.pain-guidance').isVisible() && (await savedRule()).guidance === true, 'Failed guidance save preserves enabled explanations and permits retry');
    await app.locator('[data-pain="guidance-off"]').click();
    await app.waitForFunction(() => document.querySelector('.pain-guidance').hidden);
    check(JSON.stringify(await stored()) === eventsBeforeGuidance && await app.evaluate(async before => (await (await import('/src/db.js')).get('settings', 'usage:pain')).lastUsedAt === before, usageBeforeGuidance), 'Guidance does not alter events or record use');
    check((await savedRule()).guidance === false, 'Hinweise ausblenden persists guidance false in the helper rule');
    check(await app.locator('.pain [role="status"]').textContent() === 'Hinweise ausgeblendet.', 'Guidance status confirms the action without another instruction');
    await another();
    check(!await app.locator('#pain-area-hint').isVisible() && !await app.locator('.pain fieldset').getAttribute('aria-describedby'), 'Disabled guidance hides only explanatory area copy');
    await app.reload();
    await open();
    check(!await app.locator('.pain-guidance').isVisible(), 'Guidance stays disabled after reload');
    await app.locator('[data-pain="same-area"]').click();
    check(await app.locator('.pain fieldset').getAttribute('aria-describedby') === 'pain-scale' && await app.locator('#pain-scale').isVisible(), 'Essential intensity anchors remain when guidance is disabled');
    await app.locator('input[name="intensity"][value="5"]').check();
    await app.locator('#painEntryForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('.pain-status')?.textContent === 'Eintrag gespeichert.');
    check(await app.locator('.pain-content').textContent().then(text => text.includes('Letzter dokumentierter Wert für Bauch: 3')), 'Documented prior value remains visible without guidance');
    check(await app.getByRole('heading', { name: 'Ist der Schmerz inzwischen vorbei?' }).isVisible(), 'Resolved question remains visible without guidance');
    check(!await app.locator('#pain-details-description').isVisible(), 'Optional completion copy is hidden without guidance');
    await app.locator('[data-pain="done"]').click();
    check(await app.locator('#view-dashboard').isVisible(), 'Fertig returns to the dashboard');
    await open();
    await settings();
    check(!await app.locator('input[name="guidance"]').isChecked(), 'Settings reflect disabled guidance');
    await app.locator('input[name="guidance"]').check();
    await saveRule();
    await app.locator('#backButton').click();
    await app.waitForSelector('.pain-last-value');
    check(await app.locator('.pain-guidance').isVisible(), 'Helper settings reactivate guidance');
    await settings();
    await app.locator('input[name="visible"]').uncheck();
    await saveRule();
    await app.locator('#backButton').click();
    await app.waitForFunction(() => !document.querySelector('[data-helper="pain"]'));
    check((await stored()).length === 5, 'Hiding removes dashboard entries without deleting pain data');
    await app.locator('#menuButton').click();
    await app.getByRole('button', { name: 'Verknüpfungen & Orte' }).click();
    await app.locator('.settings-block').last().evaluate(element => { element.open = true; });
    await app.locator('[data-helper-visible="pain"]').check();
    await app.waitForFunction(() => !document.querySelector('[data-helper-visible="pain"]').disabled);
    await app.locator('#backButton').click();
    await open();

    const retention = await app.evaluate(async () => {
      const db = await import('/src/db.js');
      const model = await import('/src/helpers/pain/model.js');
      const now = Date.now();
      await db.put('entries', { ...model.createObservation('Kopf', 2, now - 40 * 86400000), id: 'old-pain' });
      await db.put('entries', { id: 'old-core-note', type: 'note', text: 'Keep', createdAt: 1 });
      const rule = await db.get('helperRules', 'pain');
      await db.put('helperRules', { ...rule, trackingWindow: '30d' });
      const data = await db.exportAll();
      const oldDeleted = !data.stores.entries.some(entry => entry.id === 'old-pain');
      const noteKept = data.stores.entries.some(entry => entry.id === 'old-core-note');
      const ruleKept = data.stores.helperRules.find(value => value.id === 'pain');
      data.stores.entries.push({ ...model.createObservation('Kopf', 2, now - 40 * 86400000), id: 'expired-import' });
      await db.importAll(data);
      const importPruned = !(await db.list('entries')).some(entry => entry.id === 'expired-import');
      await db.put('helperRules', { ...rule, trackingWindow: 'always' });
      await db.put('entries', { ...model.createObservation('Kopf', 2, now - 500 * 86400000), id: 'unlimited' });
      const unlimited = (await db.exportAll()).stores.entries.some(entry => entry.id === 'unlimited');
      return { oldDeleted, noteKept, ruleKept: ruleKept.favorite && ruleKept.interval.value === 1 && ruleKept.interval.unit === 'hour', importPruned, unlimited };
    });
    for (const [name, value] of Object.entries(retention)) check(value, `Retention: ${name}`);
    await app.locator('#backButton').click();
    await open();
    await another();
    await app.locator('input[name="bodyArea"][value="Kopf"]').check();
    await next();
    await app.locator('input[name="intensity"][value="2"]').check();
    const beforeFailure = (await stored()).length;
    const usageBefore = await app.evaluate(async () => (await (await import('/src/db.js')).get('settings', 'usage:pain')).lastUsedAt);
    await app.evaluate(() => { window.originalPut = IDBObjectStore.prototype.put; IDBObjectStore.prototype.put = function() { throw new DOMException('Quota', 'QuotaExceededError'); }; });
    await app.locator('#painEntryForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('#toast').textContent.includes('Speicher voll'));
    await app.evaluate(() => { IDBObjectStore.prototype.put = window.originalPut; });
    check((await stored()).length === beforeFailure, 'Failed pain save preserves events and leaves form available');
    check(await app.evaluate(async before => (await (await import('/src/db.js')).get('settings', 'usage:pain')).lastUsedAt === before, usageBefore), 'Failed pain save does not record use');
    await app.evaluate(() => { IDBObjectStore.prototype.put = function() { throw new Error('INTERNAL entryVersion helperId'); }; });
    await app.locator('#painEntryForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('#toast').textContent === 'Konnte nicht gespeichert werden. Deine Eingabe bleibt erhalten. Bitte erneut versuchen.');
    await app.evaluate(() => { IDBObjectStore.prototype.put = window.originalPut; });
    check(await app.locator('input[name="intensity"][value="2"]').isChecked() && await app.locator('.pain-selected-area strong').textContent() === 'Kopf' && (await stored()).length === beforeFailure, 'Unknown storage failure hides internal details and preserves the pain draft');
    await app.locator('[data-pain="change-area"]').click();
    await app.locator('input[name="bodyArea"][value="Anderer Ort"]').check();
    check(!await app.locator('#painAreaForm').evaluate(form => form.checkValidity()), 'Custom area needs its own short name');
    await app.locator('input[name="otherArea"]').fill('   ');
    await app.locator('#painAreaForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('#toast').textContent === 'Bitte einen Schmerzort angeben.');
    check(await app.locator('#painAreaForm').isVisible() && (await stored()).length === beforeFailure, 'Blank custom area gives a concrete error and does not advance or save');
    await app.locator('input[name="otherArea"]').fill('Schulter');
    await next();
    await app.locator('#painEntryForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('.pain h2')?.textContent === 'Schulter · 2 gespeichert');
    check((await stored()).some(entry => entry.bodyArea === 'Schulter' && entry.intensity === 2), 'Custom named area saves as a separate event');
    await another();
    await app.locator('input[name="bodyArea"][value="Anderer Ort"]').check();
    await app.locator('input[name="otherArea"]').fill('Schulterbereich'.repeat(4));
    await next();
    await app.locator('input[name="intensity"][value="1"]').check();
    await reflow('Long custom area fits the intensity step at 320 CSS px');
    await app.locator('#painEntryForm button[type="submit"]').click();
    await app.waitForFunction(() => document.querySelector('.pain-status')?.textContent === 'Eintrag gespeichert.');
    await reflow('Long custom area fits the saved confirmation at 320 CSS px');
    await app.locator('[data-pain="done"]').click();
    await open();
    await reflow('Long custom area fits the returning summary at 320 CSS px');
    await another();
    await app.emulateMedia({ reducedMotion: 'reduce' });
    check(await app.locator('#painAreaForm button[type="submit"]').evaluate(element => parseFloat(getComputedStyle(element).transitionDuration) === 0), 'Pain respects Reduced Motion');
    check(requests.every(url => url.startsWith('http://127.0.0.1:8080/')) && !requests.some(url => url.includes('external.test')), 'No pain data or external resource requests');
    check(await app.evaluate(() => [...document.querySelectorAll('[hidden]')].every(element => getComputedStyle(element).display === 'none')), 'Hidden shell and helper controls stay hidden');
    check(errors.length === 0, `No browser errors: ${errors.join(', ')}`);
    return results;
  } finally { await context.close(); }
}
